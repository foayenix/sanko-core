// Generates the hero flow's botanical and formulation plates as inline SVG symbols.
//
// These were raster crops sliced out of a 1536px design mock. That baked the frame
// furniture, the label type and a fixed line weight into a bitmap, so every width
// other than 1536 stretched the artwork and doubled the frames. Line art is the
// one thing that must stay sharp at every size, so it is drawn parametrically here
// and spliced into index.html between the hero-plates markers.
//
// Run: node scripts/build-hero-plates.mjs

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectDirectory = path.resolve(scriptDirectory, '..');
const indexPath = path.resolve(projectDirectory, 'public', 'landing', 'index.html');
const spritePath = path.resolve(projectDirectory, 'public', 'landing', 'assets', 'hero-plates.svg');

const START = '<!-- hero-plates:start (generated by scripts/build-hero-plates.mjs) -->';
const END = '<!-- hero-plates:end -->';

const round = (n) => Math.round(n * 100) / 100;
const point = (p) => `${round(p.x)} ${round(p.y)}`;

/** Cubic through a list of points, Catmull-Rom converted to bezier. Keeps organic
 *  edges smooth without hand-tuning every control point. */
function smoothPath(points, { close = false, tension = 0.5 } = {}) {
  if (points.length < 2) return '';
  const pts = close ? [points[points.length - 1], ...points, points[0], points[1]] : [points[0], ...points, points[points.length - 1]];
  let d = `M${point(points[0])}`;
  for (let i = 1; i < pts.length - 2; i += 1) {
    const p0 = pts[i - 1];
    const p1 = pts[i];
    const p2 = pts[i + 1];
    const p3 = pts[i + 2];
    const c1 = { x: p1.x + ((p2.x - p0.x) / 6) * tension * 2, y: p1.y + ((p2.y - p0.y) / 6) * tension * 2 };
    const c2 = { x: p2.x - ((p3.x - p1.x) / 6) * tension * 2, y: p2.y - ((p3.y - p1.y) / 6) * tension * 2 };
    d += `C${point(c1)} ${point(c2)} ${point(p2)}`;
  }
  return close ? `${d}Z` : d;
}

/* ─────────────────────────── leaflets ─────────────────────────── */

// Half-width profile along a leaflet: widest just past a third of the way out,
// tapering to a point at the tip. The exponent is what separates a lance-shaped
// neem leaflet from a rounder ovate one.
function widthProfile(t, exponent) {
  return Math.sin(Math.PI * Math.pow(Math.min(Math.max(t, 0), 1), exponent));
}

/** One leaflet in local space: base at 0,0, tip at length,0.
 *  `bend` lifts the axis into a sickle curve. `teeth` sets how many times the
 *  margin turns and `serration` how deeply — they are separate because a broad
 *  ovate leaf needs a smooth outline with a shallow scallop, and tying notch
 *  count to sample count spikes the corners once the curve is smoothed. */
function leafletOutline({ length, width, exponent = 0.72, bend = 0.16, teeth = 9, serration = 0.22, veinPairs = 4, asymmetry = 0.82 }) {
  const axis = (t) => ({ x: t * length, y: -Math.sin(Math.PI * t) * bend * length });
  const samples = Math.max(teeth * 2, 24);
  const upper = [];
  const lower = [];

  for (let i = 0; i <= samples; i += 1) {
    const t = i / samples;
    const a = axis(t);
    // A cosine ripple along the margin rather than an alternating pull-in, so the
    // depth is independent of how finely the outline is sampled.
    const notch = 1 - serration * 0.5 * (1 - Math.cos(t * Math.PI * 2 * teeth));
    const w = widthProfile(t, exponent) * width * notch;
    upper.push({ x: a.x, y: a.y - w });
    lower.push({ x: a.x, y: a.y + w * asymmetry });
  }

  // The return edge continues the same subpath, so its leading moveto becomes a
  // lineto — replacing only the "M", never the coordinates that follow it.
  const outline = `${smoothPath(upper, { tension: 0.45 })}${smoothPath(lower.reverse(), { tension: 0.45 }).replace(/^M/, 'L')}Z`;
  const midribPoints = [];
  for (let i = 0; i <= 12; i += 1) midribPoints.push(axis(i / 12));
  const midrib = smoothPath(midribPoints);

  const veins = [];
  for (let i = 1; i <= veinPairs; i += 1) {
    const t = (i / (veinPairs + 1)) * 0.86;
    const a = axis(t);
    const w = widthProfile(t, exponent) * width;
    const forward = Math.min(t + 0.14, 0.97);
    const af = axis(forward);
    const wf = widthProfile(forward, exponent) * width;
    veins.push(`M${point(a)}L${point({ x: af.x, y: af.y - wf * 0.82 })}`);
    veins.push(`M${point(a)}L${point({ x: af.x, y: af.y + wf * asymmetry * 0.82 })}`);
  }

  return { outline, midrib, veins: veins.join('') };
}

function place(d, { x, y, rotate = 0, scale = 1 }) {
  const transforms = [`translate(${round(x)} ${round(y)})`];
  if (rotate) transforms.push(`rotate(${round(rotate)})`);
  if (scale !== 1) transforms.push(`scale(${round(scale)})`);
  return { d, transform: transforms.join(' ') };
}

/* ─────────────────────────── plate: neem ─────────────────────────── */

// Azadirachta indica: one pinnate compound leaf. Opposite leaflets along an
// arching rachis, shrinking toward the tip, plus a terminal leaflet.
function neemPlate() {
  const pairs = 6;
  const rachisFrom = { x: 26, y: 150 };
  const rachisTo = { x: 156, y: 34 };
  const rachisPoints = [];
  for (let i = 0; i <= 16; i += 1) {
    const t = i / 16;
    rachisPoints.push({
      x: rachisFrom.x + (rachisTo.x - rachisFrom.x) * t,
      y: rachisFrom.y + (rachisTo.y - rachisFrom.y) * t + Math.sin(Math.PI * t) * 13,
    });
  }
  const rachisAt = (t) => {
    const i = t * 16;
    const lo = Math.floor(i);
    const hi = Math.min(lo + 1, 16);
    const f = i - lo;
    return {
      x: rachisPoints[lo].x + (rachisPoints[hi].x - rachisPoints[lo].x) * f,
      y: rachisPoints[lo].y + (rachisPoints[hi].y - rachisPoints[lo].y) * f,
    };
  };
  const rachisAngle = (t) => {
    const a = rachisAt(Math.max(t - 0.02, 0));
    const b = rachisAt(Math.min(t + 0.02, 1));
    return (Math.atan2(b.y - a.y, b.x - a.x) * 180) / Math.PI;
  };

  const outlines = [];
  const midribs = [];
  const veins = [];

  for (let i = 0; i < pairs; i += 1) {
    const t = 0.12 + (i / (pairs - 1)) * 0.74;
    const anchor = rachisAt(t);
    const base = rachisAngle(t);
    const scale = 1 - (i / (pairs - 1)) * 0.42;
    const leaflet = leafletOutline({ length: 62, width: 12.5, exponent: 0.68, bend: 0.2, teeth: 9, serration: 0.26, veinPairs: 4 });

    for (const side of [-1, 1]) {
      const spread = side === -1 ? 46 : 40;
      const placed = place(leaflet.outline, { x: anchor.x, y: anchor.y, rotate: base + side * spread, scale });
      outlines.push(`<path d="${placed.d}" transform="${placed.transform}"/>`);
      const mid = place(leaflet.midrib, { x: anchor.x, y: anchor.y, rotate: base + side * spread, scale });
      midribs.push(`<path d="${mid.d}" transform="${mid.transform}"/>`);
      const vein = place(leaflet.veins, { x: anchor.x, y: anchor.y, rotate: base + side * spread, scale });
      veins.push(`<path d="${vein.d}" transform="${vein.transform}"/>`);
    }
  }

  // Terminal leaflet, carried on along the rachis line.
  const tipAnchor = rachisAt(0.93);
  const terminal = leafletOutline({ length: 46, width: 9.5, exponent: 0.68, bend: 0.14, teeth: 7, serration: 0.26, veinPairs: 3 });
  const tipAngle = rachisAngle(0.93);
  const tipPlaced = place(terminal.outline, { x: tipAnchor.x, y: tipAnchor.y, rotate: tipAngle });
  outlines.push(`<path d="${tipPlaced.d}" transform="${tipPlaced.transform}"/>`);
  const tipMid = place(terminal.midrib, { x: tipAnchor.x, y: tipAnchor.y, rotate: tipAngle });
  midribs.push(`<path d="${tipMid.d}" transform="${tipMid.transform}"/>`);

  return `
    <g class="neem-leaves">${outlines.join('')}</g>
    <g class="botanical-veins">${midribs.join('')}${veins.join('')}</g>
    <path class="botanical-stem" d="${smoothPath(rachisPoints)}"/>`;
}

/* ────────────────────── plate: ewe dongoyaro ────────────────────── */

// A branching herb rather than a single leaf, so the two plant plates read as
// different specimens at a glance instead of as the same drawing twice.
function dongoyaroPlate() {
  const stemPoints = [];
  for (let i = 0; i <= 14; i += 1) {
    const t = i / 14;
    stemPoints.push({ x: 92 - Math.sin(t * Math.PI * 0.85) * 21, y: 168 - t * 132 });
  }
  const stemAt = (t) => {
    const i = t * 14;
    const lo = Math.floor(i);
    const hi = Math.min(lo + 1, 14);
    const f = i - lo;
    return {
      x: stemPoints[lo].x + (stemPoints[hi].x - stemPoints[lo].x) * f,
      y: stemPoints[lo].y + (stemPoints[hi].y - stemPoints[lo].y) * f,
    };
  };

  const outlines = [];
  const midribs = [];
  const veins = [];
  const branches = [];

  const nodes = [0.2, 0.42, 0.63, 0.82];
  nodes.forEach((t, index) => {
    const anchor = stemAt(t);
    const scale = 1 - index * 0.15;
    // Broad, shallowly scalloped and simply veined — the neem plate next to it is
    // the finely serrated pinnate one, and two compound leaves side by side would
    // read as the same specimen drawn twice.
    const leaf = leafletOutline({ length: 54, width: 26, exponent: 1.0, bend: 0.05, teeth: 7, serration: 0.07, veinPairs: 4, asymmetry: 1 });

    for (const side of [-1, 1]) {
      const angle = side === -1 ? -164 + index * 5 : -16 - index * 5;
      const petiole = 11;
      const rad = (angle * Math.PI) / 180;
      const stalkEnd = { x: anchor.x + Math.cos(rad) * petiole, y: anchor.y + Math.sin(rad) * petiole };
      branches.push(`M${point(anchor)}L${point(stalkEnd)}`);

      const placed = place(leaf.outline, { x: stalkEnd.x, y: stalkEnd.y, rotate: angle, scale });
      outlines.push(`<path d="${placed.d}" transform="${placed.transform}"/>`);
      const mid = place(leaf.midrib, { x: stalkEnd.x, y: stalkEnd.y, rotate: angle, scale });
      midribs.push(`<path d="${mid.d}" transform="${mid.transform}"/>`);
      const vein = place(leaf.veins, { x: stalkEnd.x, y: stalkEnd.y, rotate: angle, scale });
      veins.push(`<path d="${vein.d}" transform="${vein.transform}"/>`);
    }
  });

  // Small five-petal flowers low on the plant, matching the mock's cluster.
  const flowers = [];
  const flowerSpots = [
    { x: 52, y: 148, r: 7.5 },
    { x: 70, y: 163, r: 6 },
    { x: 38, y: 166, r: 5.2 },
  ];
  for (const spot of flowerSpots) {
    for (let p = 0; p < 5; p += 1) {
      const a = (p / 5) * Math.PI * 2 - Math.PI / 2;
      const cx = spot.x + Math.cos(a) * spot.r * 0.62;
      const cy = spot.y + Math.sin(a) * spot.r * 0.62;
      flowers.push(`<ellipse cx="${round(cx)}" cy="${round(cy)}" rx="${round(spot.r * 0.46)}" ry="${round(spot.r * 0.34)}" transform="rotate(${round((a * 180) / Math.PI)} ${round(cx)} ${round(cy)})"/>`);
    }
    flowers.push(`<circle cx="${round(spot.x)}" cy="${round(spot.y)}" r="${round(spot.r * 0.2)}"/>`);
  }
  branches.push(`M${point(stemAt(0.12))}L52 148`);
  branches.push(`M${point(stemAt(0.08))}L70 163`);

  return `
    <g class="botanical-leaves">${outlines.join('')}</g>
    <g class="botanical-veins">${midribs.join('')}${veins.join('')}</g>
    <path class="botanical-stem" d="${smoothPath(stemPoints)}"/>
    <path class="botanical-stem" d="${branches.join('')}"/>
    <g class="botanical-flowers">${flowers.join('')}</g>`;
}

/* ────────────────────── plate: formulation ────────────────────── */

// Mortar, pestle and bottle. Straight geometry, drawn to the same stroke
// vocabulary as the plants so the four plates sit together.
function formulationPlate() {
  const mortar = `
    <path d="M32 94C34 120 46 136 67 136 88 136 100 120 102 94"/>
    <ellipse cx="67" cy="92" rx="35" ry="8.5"/>
    <path d="M58 136 55 150H79L76 136"/>
    <path d="M48 150H86"/>`;

  const pestle = `
    <path d="M76 96 108 52"/>
    <path d="M69 91 101 47"/>
    <path d="M101 47C104 43 111 42 115 45 119 48 119 55 116 59L108 52Z"/>`;

  const bottle = `
    <path d="M141 34H165V45H141Z"/>
    <path d="M146 45V58C146 62 140 66 138 71 136 76 136 82 136 88V138C136 143 139 146 144 146H162C167 146 170 143 170 138V88C170 82 170 76 168 71 166 66 160 62 160 58V45"/>
    <path d="M136 96H170"/>
    <path d="M136 112H170"/>`;

  return `
    <g class="vessel-mortar">${mortar}</g>
    <g class="vessel-pestle">${pestle}</g>
    <g class="vessel-bottle">${bottle}</g>`;
}

/* ─────────────────────────── output ─────────────────────────── */

const symbols = `<symbol id="plate-dongoyaro" viewBox="0 0 184 184">${dongoyaroPlate()}
  </symbol>
  <symbol id="plate-neem" viewBox="0 0 184 184">${neemPlate()}
  </symbol>
  <symbol id="plate-formulation" viewBox="0 0 200 184">${formulationPlate()}
  </symbol>`;

const block = `${START}
  <svg class="hero-plate-defs" aria-hidden="true" focusable="false"><defs>
  ${symbols}
  </defs></svg>
  ${END}`;

const html = await readFile(indexPath, 'utf8');
const startAt = html.indexOf(START);
const endAt = html.indexOf(END);
if (startAt === -1 || endAt === -1) {
  throw new Error(`Could not find the hero-plates markers in ${indexPath}. Add them before running this script.`);
}
const next = `${html.slice(0, startAt)}${block}${html.slice(endAt + END.length)}`;
await writeFile(indexPath, next, 'utf8');

await writeFile(
  spritePath,
  `<svg xmlns="http://www.w3.org/2000/svg" style="display:none"><defs>\n  ${symbols}\n</defs></svg>\n`,
  'utf8'
);

console.log('Rebuilt 3 hero plates into index.html and assets/hero-plates.svg.');
